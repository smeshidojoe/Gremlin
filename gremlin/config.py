PROFILE_WORD_SKIP_EXACT = (
    "оплата", "плачу", "пишите", "напиши", "требуются", "присылайте",
    "загляни", "цп", "₽", "💸", "claim", "make sure", "venom", "opensea",
)


def profile_word_ok(word: str) -> bool:
    """Годится ли стоп-слово сообщений для списка профилей."""
    w = (word or "").strip().lower()
    if not w or w in PROFILE_WORD_SKIP_EXACT:
        return False
    return not any(stem in w for stem in PROFILE_WORD_SKIP_STEMS)


